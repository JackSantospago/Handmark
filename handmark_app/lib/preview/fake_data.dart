/// One request already waiting on the maker, so the Requests tab and the
/// 48-hour window show something on first open.
RequestStore fakeRequests(Catalog catalog, {bool seed = true}) {
  final store = RequestStore();
  if (seed) {
    store.submit(
      catalog.piece('decanter')!,
      note: 'Could this ship to Milan before the end of the month?',
      shipTo: 'Italy',
      at: DateTime.now().subtract(const Duration(hours: 19, minutes: 20)),
    );
  }
  return store;
}
